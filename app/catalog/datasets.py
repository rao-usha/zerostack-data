def _dispatch(key, source, display_name, description, kind, grain, producer, cadence,
              tables=(), patterns=(), also=(), **kw) -> DatasetSpec:
    status = kw.pop("status", None) or _dormant(producer, *also)
    return _ds(key, source, display_name, description, kind, grain, producer, cadence,
               tables=tables, patterns=patterns, also=also, status=status, **kw)


