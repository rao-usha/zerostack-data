"""
The dataset catalog declarations (SPEC_123).

Order matters only for the dataset_registry mirror: when two datasets share
a table (``pe_firms`` is written by the SEC mart and by the legacy PE
collector), the first declaration owns the mirror row. Flagship datasets are
declared first.

Grain of the catalog: the *dataset* a customer would name. Each producer
(bulk source, dispatch key, collector, job type) maps to exactly one dataset;
wrapper producers (``irs_soi:all``, ``osha``, ``bls:series``) are
``also_produced_by`` on the dataset they write.

Tables whose names are generated at run time (``fred_{category}``,
``acs5_{year}_{table}``) are ``table_patterns``; the coverage test checks each
pattern's prefix is really generated by the producer's package.
"""

