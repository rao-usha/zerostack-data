def _ds(
    key: str,
    source: str,
    display_name: str,
    description: str,
    kind: str,
    grain: str,
    producer: str,
    cadence: str,
    rerun: str = "idempotent",
    tables: Sequence[str] = (),
    patterns: Sequence[str] = (),
    status: str = "internal",
    also: Sequence[str] = (),
    collector: Optional[str] = None,
    pii: Optional[str] = None,
    origin: Optional[str] = None,
    **kw,
) -> DatasetSpec:
    r = rights_for(key, source, collector)
    return DatasetSpec(
        key=key,
        source=source,
        display_name=display_name,
        description=description,
        kind=kind,
        grain=grain,
        producer=producer,
        cadence=cadence,
        rerun=rerun,
        tables=tuple(tables),
        table_patterns=tuple(patterns),
        also_produced_by=tuple(also),
        license=r.license,
        redistribution=r.redistribution,
        attribution=r.attribution,
        reviewed=r.reviewed,
        pii_class=pii or r.pii_class,
        origin=origin or r.origin,
        status_public=status,
        **kw,
    )


def _dormant(*producers: str) -> str:
    """internal if the nightly batch runs any of these dispatch keys, else archival."""
    keys = {p.split(":", 1)[1] for p in producers if p.startswith("dispatch:")}
    return "internal" if keys & BATCH_SCHEDULED_DISPATCH else "archival"


